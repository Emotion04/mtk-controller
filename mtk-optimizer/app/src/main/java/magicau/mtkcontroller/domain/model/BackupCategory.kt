package magicau.mtkcontroller.domain.model

/**
 * 备份里可以单独取舍的几类内容。
 *
 * ## 为什么按类而不是整体
 *
 * 三类东西的用途和风险都不同：
 *
 *  - **方案** 是用户调出来的频率与档位组合，跨机可复用，也最值得备份
 *  - **应用偏好** 是主题、圆角、默认标签这类外观选择，换机后想带过去
 *  - **厂商配置备份** 是从固件里读出来的原始配置，只在同机型上有意义
 *
 * 整体导出会让"我只想搬方案"这个最常见的需求被迫连厂商配置一起带走 ——
 * 而那份东西在别的机型上是无效的，导入时还可能覆盖对的东西。
 *
 * ## 导入时同样按类生效
 *
 * 导出的取舍在文件里，导入的取舍在应用时。两者分开是因为用户可能拿到
 * 别人给的备份文件，只想取其中一部分。
 */
enum class BackupCategory {
    /** 保存的方案（含当前激活的是哪个）。 */
    PROFILES,

    /** 主题、圆角、动效、底栏样式这些应用自身的偏好。 */
    PREFERENCES,

    /** 从固件读出的厂商配置备份。只在同机型上有意义。 */
    SMART_PLATFORM,
    ;

    companion object {
        /** 默认全选：导出时"全都要"是最不意外的默认。 */
        val ALL: Set<BackupCategory> = entries.toSet()
    }
}
